package semai

import "testing"

// «Сколько в коробке и в вазе?» / «Сколько всего?» — сумма по местам, а не только первое место.
func TestEventsSumOfPlaces(t *testing.T) {
	st := "В коробке было 8 конфет, в вазе 6 конфет. Маша взяла 3 конфеты из коробки, потом Петя положил 5 конфет в вазу, потом Маша положила 2 конфеты в коробку."
	cases := []struct{ q, want string }{
		{"Сколько конфет стало в коробке?", "7"},
		{"Сколько конфет в вазе?", "11"},
		{"Сколько конфет в коробке и в вазе?", "18"},
		{"Сколько всего конфет в коробке и вазе?", "18"},
		{"Сколько всего конфет?", "18"},
	}
	for _, c := range cases {
		a := SolveEvents(st, c.q)
		got := "<nil>"
		if a != nil {
			got = a.Answer
		}
		t.Logf("%s → %s", c.q, got)
		if got != c.want {
			t.Errorf("%s: got %s, want %s", c.q, got, c.want)
		}
	}
}
