package semai

import "testing"

// Сравнение двух мест: разница концов, а не изменение первого места.
func TestEventsCompare(t *testing.T) {
	st := "В коробке было 14 конфет, в вазе 5 конфет. Маша взяла 4 конфеты из коробки, потом Петя положил 3 конфеты в вазу, потом мама положила 2 конфеты в коробку."
	cases := []struct{ q, want string }{
		{"На сколько конфет в коробке больше, чем в вазе?", "4"},
		{"Сколько конфет в коробке больше, чем в вазе?", "4"},
		{"На сколько конфет в вазе меньше, чем в коробке?", "4"},
		{"Больше ли конфет в коробке, чем в вазе?", "yes"},
		{"Меньше ли конфет в коробке, чем в вазе?", "no"},
		{"На сколько уменьшилось количество конфет в коробке?", "2"},
		{"Сколько конфет в коробке и в вазе?", "20"},
	}
	for _, c := range cases {
		a := SolveEvents(st, c.q)
		got := "<nil>"
		if a != nil {
			got = a.Answer
		}
		t.Logf("%s → %s", c.q, got)
		if got != c.want {
			t.Errorf("%s: got %s, want %s", c.q, got, c.want)
		}
	}
}
