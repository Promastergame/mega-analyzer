package semai

import "testing"

// «…, делённое на 2» — действие над итогом: (13 + 8) / 2, а не третья куча конфет.
func TestEventsPostOp(t *testing.T) {
	base := "В коробке было 15 конфет, в вазе 9 конфет. Маша переложила 4 конфеты из коробки в вазу, потом Петя съел 3 конфеты из вазы, потом Маша переложила 2 конфеты из вазы обратно в коробку"
	want := trimNum(10.5)
	cases := []struct{ st, q, want string }{
		{base + ".", "Сколько конфет в коробке и в вазе?", "21"},
		{base + ", деленное на 2.", "Сколько конфет в коробке и в вазе?", want},
		{base + ".", "Сколько конфет в коробке и в вазе, делённое на 2?", want},
		{base + ".", "Сколько конфет в коробке?", "13"},
		{base + ", умноженное на 2.", "Сколько конфет в коробке?", "26"},
	}
	for _, c := range cases {
		a := SolveEvents(c.st, c.q)
		got := "<nil>"
		if a != nil {
			got = a.Answer
		}
		t.Logf("%s | %s → %s", c.st[len(c.st)-30:], c.q, got)
		if got != c.want {
			t.Errorf("%s: got %s, want %s", c.q, got, c.want)
		}
	}
}
