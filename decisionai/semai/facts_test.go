package semai

import "testing"

func TestSolveFacts(t *testing.T) {
	cases := []struct{ state, q, want string }{
		{"У игрока 7 монет. Цена меча — 10 монет. Скидка не активна.", "Может ли игрок купить меч?", "no"},
		{"У игрока 12 монет. Цена меча — 10 монет.", "Может ли игрок купить меч?", "yes"},
		{"У Пети есть 5 рублей. Игрушка стоит 1 рубль.", "Может ли Петя купить 10 игрушек?", "no"},
		{"У Пети есть 50 рублей. Игрушка стоит 3 рубля.", "Может ли Петя купить 10 игрушек?", "yes"},
		{"В магазине есть 5 игрушек, но Петя хочет купить 10. У Пети 100 рублей. Игрушка стоит 2 рубля.", "Может ли Петя купить 10 игрушек?", "no"},
		{"У Маши 20 рублей, у Пети 5 рублей. Мяч стоит 15 рублей.", "Кто может купить мяч?", "yes"},
		{"У Маши 20 рублей. Мяч стоит 25 рублей. Скидка 20% активна.", "Может ли Маша купить мяч?", "yes"},
		{"", "У Васи 3 яблока. Может ли он купить грушу за 5 яблок?", "no"},
		{"У игрока 7 монет.", "Может ли игрок купить меч?", "unknown"},
		{"У игрока 7 монет. Меч стоит 5 рублей.", "Может ли игрок купить меч?", "unknown"},
		{"На столе 6 кусочков пиццы, а друзей пришло 8", "Хватит ли пиццы на всех друзей?", "no"},
		{"На столе 12 кусочков пиццы, друзей 4, каждому по 3 кусочка", "Хватит ли пиццы на всех друзей?", "yes"},
		{"В магазине есть 5 игрушек но я хочу купить 10 игрушек", "Может ли кто-то купить 10 игрушек?", "no"},
		{"У игрока семь монет. Меч стоит десять монет.", "Может ли игрок купить меч?", "no"},
	}
	for _, c := range cases {
		fa := SolveFacts(c.state, c.q)
		if fa == nil || fa.Answer != c.want {
			t.Errorf("%q / %q: got %+v, want %s", c.state, c.q, fa, c.want)
		} else {
			t.Logf("%s %v %v", fa.Answer, fa.Who, fa.Reasoning)
		}
	}
	if SolveFacts("x", "Сколько ушей у 3,5 мыши?") != nil {
		t.Error("not a purchase question")
	}
}
