package semai

import "testing"

func TestEventsGNN(t *testing.T) {
	if EventModel() == nil {
		t.Skip("event GNN not bundled")
	}
	cases := []struct{ state, q, want string }{
		{"Мальчик взял из коробки 3 конфеты, потом вернул 2 обратно, потом взял ещё 5", "Стало ли конфет в коробке меньше, чем было вначале?", "yes"},
		{"Мальчик взял из коробки 3 конфеты, потом вернул 2 обратно, потом взял ещё 5", "Стало ли конфет в коробке больше, чем было вначале?", "no"},
		{"Мальчик взял из коробки 3 конфеты, потом вернул 2 обратно, потом взял ещё 5", "Стало ли у мальчика больше конфет?", "yes"},
		{"В копилке было 40 монет. Петя достал из копилки 15 монет, потом положил обратно 7, затем мама добавила в копилку 10 монет", "Сколько монет стало в копилке?", "42"},
		{"Маша положила в вазу 4 яблока, потом достала из вазы 4 яблока", "Изменилось ли количество яблок в вазе?", "no"},
	}
	for _, c := range cases {
		a := SolveFacts(c.state, c.q)
		if a == nil || a.Answer != c.want {
			t.Errorf("%s | %s: got %+v", c.state, c.q, a)
		}
	}
}
