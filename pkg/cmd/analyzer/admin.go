// File profiles cannot authorize elevation. Inspect only caller arguments,
// skipping value-taking flags using the actual CLI registrations.
func commandLineBool(args []string, fs *flag.FlagSet, name string) bool {
	value := false
	for i := 0; i < len(args); i++ {
		arg := args[i]
		if arg == "--" {
			break
		}
		if !strings.HasPrefix(arg, "-") {
			continue
		}
		key, text, hasValue := strings.Cut(strings.TrimLeft(arg, "-"), "=")
		f := fs.Lookup(key)
		if f == nil {
			continue
		}
		b, ok := f.Value.(boolFlag)
		if !ok || !b.IsBoolFlag() {
			if !hasValue {
				i++
			}
			continue
		}
		if key == name {
			if !hasValue {
				value = true
			} else if v, e := strconv.ParseBool(text); e == nil {
				value = v
			}
		}
	}
	return value
}

func validateAdminFlags(opts *CLIOptions, fs *flag.FlagSet, caller []string) error {
	if !opts.Admin {
		if opts.adminRelaunched || opts.adminCWD != "" {
			return fmt.Errorf("internal admin restart options require -web -admin")
		}
		return nil
	}
	if !commandLineBool(caller, fs, "admin") {
		return fmt.Errorf("-admin must be explicit on the command line, not enabled by a profile")
	}
	if !opts.Web {
		return fmt.Errorf("-admin works only with -web; use: analyzer -web -admin")
	}
	if opts.WebPort < 1 || opts.WebPort > 65535 {
		return fmt.Errorf("-web-port must be between 1 and 65535")
	}
	allowed := map[string]bool{"web": true, "admin": true, "web-port": true, "web-ui-token": true, "no-profile": true, "help": true, "h": true, "version": true, "v": true, "admin-reexec": true, "admin-cwd": true, "no-tui": true, "no-color": true, "quiet": true, "q": true}
	invalid := ""
	fs.Visit(func(f *flag.Flag) {
		if !allowed[f.Name] && invalid == "" {
			invalid = f.Name
		}
	})
	if invalid != "" || opts.Target != "" {
		return fmt.Errorf("-admin accepts only web startup options (unexpected option/target %q); configure analyses in the web UI", invalid)
	}
	if opts.adminCWD != "" && (!opts.adminRelaunched || !filepath.IsAbs(opts.adminCWD)) {
		return fmt.Errorf("admin restart directory must be absolute and accompanied by the restart marker")
	}
	opts.NoProfile = true
	return nil
}

func runAdminWeb(opts *CLIOptions) error {
	return runAdminWebWith(opts, processIsElevated, restartElevated, runWebUIOptions)
}

// Tests inject these operations: no real UAC/sudo/su or server is started.
func runAdminWebWith(opts *CLIOptions, check func() (bool, error), restart func(string, []string, string) error, serve func(*CLIOptions) error) error {
	if opts == nil || !opts.Web || !opts.Admin {
		return fmt.Errorf("-admin works only with -web")
	}
	if opts.WebPort < 1 || opts.WebPort > 65535 {
		return fmt.Errorf("-web-port must be between 1 and 65535")
	}
	if opts.Help {
		NewCLIParser().printUsage()
		return nil
	}
	if opts.Version {
		(&App{opts: opts}).printVersion()
		return nil
	}
	if err := validateAdminHost(os.Getenv("MEGA_ANALYZER_HOST")); err != nil {
		return err
	}
	if err := validateAdminToken(opts.WebToken); err != nil {
		return err
	}
	elevated, err := check()
	if err != nil {
		return fmt.Errorf("cannot inspect administrator/root privileges: %w", err)
	}
	if !elevated {
		if opts.adminRelaunched {
			return fmt.Errorf("restarted process is still not administrator/root; refusing another elevation attempt")
		}
		exe, err := os.Executable()
		if err != nil {
			return err
		}
		cwd, err := os.Getwd()
		if err != nil {
			return fmt.Errorf("cannot preserve working directory: %w", err)
		}
		fmt.Fprintln(os.Stderr, "Requesting administrator/root access for the local web UI through the operating system.")
		return restart(exe, adminRestartArgs(opts, cwd), cwd)
	}
	if opts.adminCWD != "" {
		if err := os.Chdir(opts.adminCWD); err != nil {
			return fmt.Errorf("cannot restore administrator working directory: %w", err)
		}
	}
	return serve(opts)
}

func validateAdminHost(host string) error {
	host = strings.TrimSpace(host)
	if host == "" || strings.EqualFold(host, "localhost") {
		return nil
	}
	if ip := net.ParseIP(host); ip != nil && ip.IsLoopback() {
		return nil
	}
	return fmt.Errorf("-admin permits only a loopback listener; unset MEGA_ANALYZER_HOST or use 127.0.0.1/::1")
}
func validateAdminToken(token string) error {
	if token == "" {
		return nil
	} // generated by child, never put fresh secrets in argv
	if len(token) < 32 || len(token) > 256 {
		return fmt.Errorf("explicit administrator token requires 32–256 URL-safe ASCII characters; omit it for a fresh token")
	}
	for _, c := range token {
		if !(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || c == '_' || c == '-') {
			return fmt.Errorf("administrator token may contain only letters, digits, '_' and '-'")
		}
	}
	return nil
}
func adminRestartArgs(opts *CLIOptions, cwd string) []string {
	args := []string{"-web", "-admin", "-admin-reexec", "-no-profile", "-web-port", strconv.Itoa(opts.WebPort), "-admin-cwd", cwd}
	if opts.WebToken != "" {
		args = append(args, "-web-ui-token", opts.WebToken)
	}
	return args
}

// Windows CRT quoting, without cmd.exe/PowerShell interpolation.
func quoteWindowsArg(arg string) string {
	var b strings.Builder
	b.WriteByte('"')
	slashes := 0
	for _, c := range arg {
		if c == '\\' {
			slashes++
			continue
		}
		if c == '"' {
			b.WriteString(strings.Repeat("\\", 2*slashes+1))
		} else {
			b.WriteString(strings.Repeat("\\", slashes))
		}
		slashes = 0
		b.WriteRune(c)
	}
	b.WriteString(strings.Repeat("\\", 2*slashes))
	b.WriteByte('"')
	return b.String()
}
func windowsAdminParameters(args []string) (string, error) {
	parts := make([]string, len(args))
	for i, arg := range args {
		if strings.ContainsRune(arg, 0) {
			return "", fmt.Errorf("administrator arguments cannot contain NUL")
		}
		parts[i] = quoteWindowsArg(arg)
	}
	return strings.Join(parts, " "), nil
}
func quotePOSIXArg(arg string) string { return "'" + strings.ReplaceAll(arg, "'", "'\"'\"'") + "'" }
func androidAdminCommand(exe string, args []string) (string, error) {
	parts := append([]string{exe}, args...)
	for i, p := range parts {
		if strings.ContainsRune(p, 0) {
			return "", fmt.Errorf("administrator arguments cannot contain NUL")
		}
		parts[i] = quotePOSIXArg(p)
	}
	return "exec " + strings.Join(parts, " "), nil
}
