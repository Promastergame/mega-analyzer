package fusion

// itoa is a tiny, allocation-light integer formatter used for synthetic ids
// and feature names. Kept local so the package does not pull strconv into hot
// paths for trivial conversions.
func itoa(i int) string {
	if i == 0 {
		return "0"
	}
	neg := i < 0
	if neg {
		i = -i
	}
	var buf [20]byte
	pos := len(buf)
	for i > 0 {
		pos--
		buf[pos] = byte('0' + i%10)
		i /= 10
	}
	if neg {
		pos--
		buf[pos] = '-'
	}
	return string(buf[pos:])
}

// clamp01 bounds x into [0,1]. Shared across the package's scoring paths.
func clamp01(x float64) float64 {
	if x < 0 {
		return 0
	}
	if x > 1 {
		return 1
	}
	return x
}
