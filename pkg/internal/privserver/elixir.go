func elixirAppName(module string) string {
	var b strings.Builder
	for i, r := range module {
		if r >= 'A' && r <= 'Z' {
			if i > 0 {
				b.WriteByte('_')
			}
			b.WriteRune(r + ('a' - 'A'))
			continue
		}
		b.WriteRune(r)
	}
	out := b.String()
	if out == "" {
		return "private_server"
	}
	return out
}

func elixirString(s string) string {
	escaped := strings.ReplaceAll(s, "\\", "\\\\")
	escaped = strings.ReplaceAll(escaped, "\"", "\\\"")
	return "\"" + escaped + "\""
}

func elixirAtom(s string) string {
	out := strings.ToLower(strings.TrimSpace(s))
	if out == "" {
		return "unknown"
	}
	var b strings.Builder
	for i, r := range out {
		switch {
		case r >= 'a' && r <= 'z':
			b.WriteRune(r)
		case r >= '0' && r <= '9' && i > 0:
			b.WriteRune(r)
		case r == '_' && i > 0:
			b.WriteRune(r)
		case r == '-':
			b.WriteByte('_')
		}
	}
	if b.Len() == 0 {
		return "unknown"
	}
	return b.String()
}

func elixirAtomString(s string) string {
	return ":" + elixirAtom(s)
}

