package pipeline

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"mega-analyzer/pkg/internal/types"
)

// GenerateUnpackScript creates a PowerShell script to extract hidden payloads
func GenerateUnpackScript(analysis *types.AnalysisResult, outputPath string) error {
	var sb strings.Builder
	sb.WriteString("# PowerShell script to extract hidden payloads from media files\n")
	sb.WriteString("# Auto-generated by Mega-Analyzer\n\n")

	hasExtraction := false

	for _, file := range analysis.Files {
		if file.MediaData == nil || len(file.MediaData.Regions) == 0 {
			continue
		}

		for i, reg := range file.MediaData.Regions {
			size := reg.EndOffset - reg.StartOffset
			if size <= 0 {
				continue
			}
			hasExtraction = true

			typ := "data"
			if len(reg.DominantSignals) > 0 {
				typ = reg.DominantSignals[0]
			}

			// Define variables
			sb.WriteString(fmt.Sprintf("$inFile = '%s'\n", file.Path))
			sb.WriteString(fmt.Sprintf("$outDir = Join-Path -Path $extractDir -ChildPath '%s_extracted'\n", filepath.Base(file.Path)))
			sb.WriteString("if (!(Test-Path $outDir)) { New-Item -ItemType Directory -Force -Path $outDir | Out-Null }\n")

			outName := fmt.Sprintf("region_%d_%s_%d.bin", i, typ, reg.StartOffset)
			sb.WriteString(fmt.Sprintf("$outFile = Join-Path -Path $outDir -ChildPath '%s'\n", outName))

			// Write extraction logic
			sb.WriteString(fmt.Sprintf("Write-Host 'Extracting %s (offset: 0x%x, size: %d bytes)...'\n", outName, reg.StartOffset, size))
			sb.WriteString("$stream = [System.IO.File]::OpenRead($inFile)\n")
			sb.WriteString(fmt.Sprintf("$stream.Seek(%d, [System.IO.SeekOrigin]::Begin) | Out-Null\n", reg.StartOffset))
			sb.WriteString(fmt.Sprintf("$buffer = New-Object byte[] %d\n", size))
			sb.WriteString("$read = $stream.Read($buffer, 0, $buffer.Length)\n")
			sb.WriteString("$stream.Close()\n")
			sb.WriteString("[System.IO.File]::WriteAllBytes($outFile, $buffer)\n\n")
		}
	}

	if !hasExtraction {
		// Nothing to extract
		return nil
	}

	return os.WriteFile(outputPath, []byte(sb.String()), 0644)
}
