package correlation

import (
	"fmt"
	"strings"
	"time"
)

// RenderMarkdown produces an analyst-facing Markdown report. It is
// intentionally section-by-section so individual sections can be
// reused later if the engine is embedded into a larger report.
func RenderMarkdown(r *Result) string {
	if r == nil {
		return "# Correlation Report\n\n*No data.*\n"
	}

	var b strings.Builder
	b.Grow(8 * 1024)

	b.WriteString("# 🔗 Correlation & Attack-Chain Report\n\n")
	if r.SessionID != "" {
		fmt.Fprintf(&b, "- **Session ID**: `%s`\n", r.SessionID)
	}
	fmt.Fprintf(&b, "- **Generated**: `%s`\n", r.GeneratedAt.UTC().Format(time.RFC3339))
	fmt.Fprintf(&b, "- **Inputs**: runtime=%v, static=%v\n", r.HasRuntime, r.HasStatic)
	fmt.Fprintf(&b, "- **Overall risk**: %s **%s**\n", riskEmoji(r.OverallRisk), r.OverallRisk)
	fmt.Fprintf(&b, "- **Overall likelihood**: %s\n", r.OverallLikeli)
	b.WriteString("\n")

	if len(r.Notes) > 0 {
		b.WriteString("> ")
		for i, n := range r.Notes {
			if i > 0 {
				b.WriteString("  \n> ")
			}
			b.WriteString(n)
		}
		b.WriteString("\n\n")
	}

	renderStatsMD(&b, r.Stats)
	renderChainsMD(&b, r.Chains)
	renderFindingsMD(&b, r.Findings)
	renderTimelineMD(&b, r.Timeline)

	b.WriteString("---\n\n")
	b.WriteString("*Generated by APK Analyzer correlation engine — post-processing stage.*\n")
	return b.String()
}

func renderStatsMD(b *strings.Builder, s ResultStats) {
	b.WriteString("## 📊 At a glance\n\n")
	b.WriteString("| Signals | Static | Runtime | Findings | Chains | High | Critical |\n")
	b.WriteString("|---------|--------|---------|----------|--------|------|----------|\n")
	fmt.Fprintf(b, "| %d | %d | %d | %d | %d | %d | %d |\n\n",
		s.TotalSignals, s.StaticSignals, s.RuntimeSignals,
		s.TotalFindings, s.TotalChains, s.HighRisks, s.CriticalRisks)
}

func renderChainsMD(b *strings.Builder, chains []AttackChain) {
	b.WriteString("## ⛓ Attack Chains\n\n")
	if len(chains) == 0 {
		b.WriteString("*No attack chains matched.*\n\n")
		return
	}
	for _, c := range chains {
		fmt.Fprintf(b, "### %s %s\n\n", riskEmoji(c.Risk), c.Name)
		fmt.Fprintf(b, "- **Risk**: %s\n", c.Risk)
		fmt.Fprintf(b, "- **Likelihood**: %s\n", c.Likelihood)
		fmt.Fprintf(b, "- **Involved components**: %s\n", joinKinds(c.InvolvedKinds))
		if c.ProcessKey != "" && c.ProcessKey != "static" {
			fmt.Fprintf(b, "- **Process**: `%s`\n", c.ProcessKey)
		}
		if len(c.MITRETechniques) > 0 {
			fmt.Fprintf(b, "- **MITRE**: `%s`\n", strings.Join(c.MITRETechniques, "`, `"))
		}
		fmt.Fprintf(b, "- **Likelihood factors**: reachable=%t, controllable=%t, observed_at_runtime=%t\n",
			c.Factors.Reachable, c.Factors.Controllable, c.Factors.ObservedAtRuntime)
		b.WriteString("\n")

		if c.Description != "" {
			fmt.Fprintf(b, "> %s\n\n", c.Description)
		}

		if len(c.Sequence) > 0 {
			b.WriteString("**Sequence**:\n\n")
			for _, step := range c.Sequence {
				fmt.Fprintf(b, "%d. **[%s]** %s", step.Order,
					step.Component, step.Title)
				if !step.Timestamp.IsZero() {
					fmt.Fprintf(b, " — `%s`", step.Timestamp.UTC().Format(time.RFC3339))
				}
				b.WriteString("\n")
				if step.Description != "" {
					fmt.Fprintf(b, "    - %s\n", step.Description)
				}
				for _, sig := range step.Signals {
					if sig == nil {
						continue
					}
					fmt.Fprintf(b, "    - evidence: `%s` (`%s`)\n", sig.Title, sig.ID)
				}
			}
			b.WriteString("\n")
		}

		if len(c.Evidence) > 0 {
			b.WriteString("**Evidence**:\n")
			for _, sig := range c.Evidence {
				fmt.Fprintf(b, "- `%s` — %s\n", sig.Type, sig.Title)
			}
			b.WriteString("\n")
		}

		if c.Explanation != "" {
			fmt.Fprintf(b, "**Why this matters**: %s\n\n", c.Explanation)
		}

		if len(c.Mitigations) > 0 {
			b.WriteString("**Mitigations**:\n")
			for _, m := range c.Mitigations {
				fmt.Fprintf(b, "- %s\n", m)
			}
			b.WriteString("\n")
		}
		if len(c.Workarounds) > 0 {
			b.WriteString("**Research workarounds (how to verify safely)**:\n")
			for _, w := range c.Workarounds {
				fmt.Fprintf(b, "- %s\n", w)
			}
			b.WriteString("\n")
		}
		b.WriteString("---\n\n")
	}
}

func renderFindingsMD(b *strings.Builder, findings []Finding) {
	b.WriteString("## 🔍 Findings\n\n")
	if len(findings) == 0 {
		b.WriteString("*No standalone findings (everything is consumed by attack chains).*\n\n")
		return
	}

	b.WriteString("| Risk | Likelihood | Title | Category | Reach / Control / Observed |\n")
	b.WriteString("|------|------------|-------|----------|----------------------------|\n")
	for _, f := range findings {
		fmt.Fprintf(b, "| %s %s | %s | %s | %s | %s |\n",
			riskEmoji(f.Risk), f.Risk, f.Likelihood, escapePipe(f.Title), f.Category,
			factorsShort(f.Factors))
	}
	b.WriteString("\n")

	for _, f := range findings {
		fmt.Fprintf(b, "### %s %s\n\n", riskEmoji(f.Risk), f.Title)
		fmt.Fprintf(b, "- **Risk**: %s\n", f.Risk)
		fmt.Fprintf(b, "- **Likelihood**: %s\n", f.Likelihood)
		fmt.Fprintf(b, "- **Category**: `%s`\n", f.Category)
		if f.Location != nil && f.Location.File != "" {
			loc := f.Location.File
			if f.Location.Line > 0 {
				loc = fmt.Sprintf("%s:%d", f.Location.File, f.Location.Line)
			}
			fmt.Fprintf(b, "- **Location**: `%s`\n", loc)
		}
		fmt.Fprintf(b, "- **Likelihood factors**: reachable=%t, controllable=%t, observed_at_runtime=%t\n",
			f.Factors.Reachable, f.Factors.Controllable, f.Factors.ObservedAtRuntime)
		if f.Factors.RuntimeEvidence != "" {
			fmt.Fprintf(b, "  - runtime evidence: %s\n", f.Factors.RuntimeEvidence)
		}
		if f.Factors.ReachReason != "" {
			fmt.Fprintf(b, "  - reach reason: %s\n", f.Factors.ReachReason)
		}
		if f.Factors.ControlReason != "" {
			fmt.Fprintf(b, "  - control reason: %s\n", f.Factors.ControlReason)
		}
		b.WriteString("\n")

		if f.Explanation != "" {
			fmt.Fprintf(b, "> %s\n\n", f.Explanation)
		}

		if len(f.Evidence) > 0 {
			b.WriteString("**Evidence**:\n")
			for _, sig := range f.Evidence {
				fmt.Fprintf(b, "- `%s` — %s", sig.Type, sig.Title)
				if sig.PID > 0 {
					fmt.Fprintf(b, " (pid=%d)", sig.PID)
				}
				if sig.Target != "" {
					fmt.Fprintf(b, " → `%s`", sig.Target)
				}
				b.WriteString("\n")
				for _, e := range sig.Evidence {
					fmt.Fprintf(b, "  - %s\n", e)
				}
			}
			b.WriteString("\n")
		}

		if len(f.RelatedEvents) > 0 {
			b.WriteString("**Related runtime events**:\n")
			for _, sig := range f.RelatedEvents {
				fmt.Fprintf(b, "- `%s` — %s\n", sig.Type, sig.Title)
			}
			b.WriteString("\n")
		}

		if len(f.Mitigations) > 0 {
			b.WriteString("**Mitigations**:\n")
			for _, m := range f.Mitigations {
				fmt.Fprintf(b, "- %s\n", m)
			}
			b.WriteString("\n")
		}
		if len(f.Workarounds) > 0 {
			b.WriteString("**Research workarounds (how to verify safely)**:\n")
			for _, w := range f.Workarounds {
				fmt.Fprintf(b, "- %s\n", w)
			}
			b.WriteString("\n")
		}
		b.WriteString("---\n\n")
	}
}

func renderTimelineMD(b *strings.Builder, events []TimelineEvent) {
	if len(events) == 0 {
		return
	}
	b.WriteString("## 🕒 Timeline\n\n")
	b.WriteString("| # | Time | Process | Kind | Title | Target |\n")
	b.WriteString("|---|------|---------|------|-------|--------|\n")
	limit := len(events)
	if limit > 50 {
		limit = 50
	}
	for i := 0; i < limit; i++ {
		ev := events[i]
		fmt.Fprintf(b, "| %d | `%s` | `%s` | `%s` | %s | `%s` |\n",
			ev.Order, ev.Timestamp.UTC().Format("15:04:05.000"),
			emptyDash(ev.ProcessKey), ev.Kind,
			escapePipe(ev.Title), emptyDash(ev.Target))
	}
	if len(events) > 50 {
		fmt.Fprintf(b, "\n*…and %d more in the JSON report.*\n", len(events)-50)
	}
	b.WriteString("\n")
}

func riskEmoji(r Risk) string {
	switch r {
	case RiskCritical:
		return "🔴"
	case RiskHigh:
		return "🟠"
	case RiskMedium:
		return "🟡"
	case RiskLow:
		return "🟢"
	default:
		return "⚪"
	}
}

func joinKinds(ks []SignalKind) string {
	if len(ks) == 0 {
		return "—"
	}
	parts := make([]string, len(ks))
	for i, k := range ks {
		parts[i] = string(k)
	}
	return strings.Join(parts, ", ")
}

func factorsShort(f LikelihoodFactors) string {
	mark := func(b bool) string {
		if b {
			return "✓"
		}
		return "·"
	}
	return fmt.Sprintf("R %s / C %s / O %s",
		mark(f.Reachable), mark(f.Controllable), mark(f.ObservedAtRuntime))
}

func emptyDash(s string) string {
	if s == "" {
		return "—"
	}
	return s
}

func escapePipe(s string) string {
	return strings.ReplaceAll(s, "|", "\\|")
}
